-- Wave 2 | PG_SILVER.SAOKE_TINDUNG – SNAPSHOT (Business Credit Statement)
-- Sheet 'SAOKE_TINDUNG': 67 cột. main = T24CORE_LD_LOANS_AND_DEPOSITS (ld) + CUSTOMER (cus) + DEPT_ACCT_OFFICER (dao)
-- Grain: 1 dòng / hợp đồng LD (khác REVE) tại ${ETL_DATE}.
{{ config(materialized='incremental', incremental_strategy='append', partition_by=['ETL_DATE'],
          pre_hook="{{ delete_partition('ETL_DATE') }}", alias='saoke_tindung') }}

with ld as (
    select * from {{ bz('t24core_ld_loans_and_deposits') }} where nvl(RECORD_STATUS, '_') <> 'REVE'
),
cus as (select * from {{ bz('t24core_customer') }}),
dao as (select * from {{ bz('t24core_dept_acct_officer') }})
select
    TRIM(cus.INTERNET_BANKING_SERVICE) as INTERNET_BANKING_SERVICE,
    TRIM(cus.KHOI) as KHOI,
    TRIM(cus.KYC_CHANNEL) as KYC_CHANNEL,
    TRIM(cus.MA_BHXH) as MA_BHXH,
    TRIM(cus.MAU_HD) as MAU_HD,
    TRIM(cus.MB_CR_STT) as MB_CR_STT,
    TRIM(cus.MB_INDUSTRY) as MB_INDUSTRY,
    TRIM(cus.MB_RM_BANCHEO) as MB_RM_BANCHEO,
    TRIM(cus.MOBILE_BANKING_SERVICE) as MOBILE_BANKING_SERVICE,
    TRIM(cus.MOBILE_NUMBER) as MOBILE_NUMBER,
    {{ t24_date('cus.NAT_ID_EXP_DATE') }} as NAT_ID_EXP_DATE,
    {{ t24_date('cus.NAT_ID_ISS_DATE') }} as NAT_ID_ISS_DATE,
    TRIM(cus.NAT_ID_ISS_PLC) as NAT_ID_ISS_PLC,
    TRIM(cus.NAT_ID_TYPE) as NAT_ID_TYPE,
    TRIM(cus.NATIONAL_ID) as NATIONAL_ID,
    TRIM(cus.NATIONALITY) as NATIONALITY,
    COALESCE(CAST(cus.NET_MONTHLY_IN AS DECIMAL(25,5)), 0) as NET_MONTHLY_IN,
    TRIM(cus.NO_LIEN_DOI) as NO_LIEN_DOI,
    TRIM(cus.OCCUPATION) as OCCUPATION,
    TRIM(cus.OPEN_COMPANY) as OPEN_COMPANY,
    TRIM(cus.PHONE_CONT_PER) as PHONE_CONT_PER,
    TRIM(cus.RECID) as CUS_RECID,
    TRIM(cus.REFERRED_BY) as REFERRED_BY,
    TRIM(cus.RESID_PROVINCE) as RESID_PROVINCE,
    TRIM(cus.RESIDENCE) as RESIDENCE,
    TRIM(cus.SECOND_OFFICER) as SECOND_OFFICER,
    TRIM(cus.SECTOR) as SECTOR,
    TRIM(cus.SHORT_NAME) as SHORT_NAME,
    TRIM(cus.STREET) as STREET,
    TRIM(cus.TARGET) as TARGET,
    TRIM(cus.TAX_SERIAL) as TAX_SERIAL,
    {{ t24_date('cus.TXN_DATE') }} as TXN_DATE,
    {{ t24_date('cus.VAT_INV_DATE') }} as VAT_INV_DATE,
    TRIM(cus.VAT_INV_SERIAL) as VAT_INV_SERIAL,
    TRIM(cus.VIP_CUSTOMER) as VIP_CUSTOMER,
    TRIM(cus.VN_FULL_NAME) as VN_FULL_NAME,
    TRIM(cus.VN_GENDER) as VN_GENDER,
    TRIM(cus.VN_STREET) as VN_STREET,
    TRIM(cus.VN_TOWN) as VN_TOWN,
    TRIM(dao.NAME) as NAME,
    TRIM(dao.RECID) as DAO_RECID,
    TRIM(ld.ACC_FCC) as ACC_FCC,
    COALESCE(CAST(ld.AMOUNT AS DECIMAL(25,5)), 0) as AMOUNT,
    COALESCE(CAST(ld.APPROVE_AMOUNT AS DECIMAL(25,5)), 0) as APPROVE_AMOUNT,
    TRIM(ld.AUTHORISER) as AUTHORISER,
    TRIM(ld.CATEGORY) as CATEGORY,
    TRIM(ld.CO_CODE) as CO_CODE,
    TRIM(ld.COMMIT_ACTION) as COMMIT_ACTION,
    TRIM(ld.CRA_LD) as CRA_LD,
    COALESCE(CAST(ld.CURR_NO AS DECIMAL(10)), 0) as CURR_NO,
    TRIM(ld.CURRENCY) as CURRENCY,
    TRIM(ld.CUSTOMER_ID) as CUSTOMER_ID,
    {{ t24_date('ld.DATE_TIME') }} as DATE_TIME,
    COALESCE(CAST(ld.DRAWDOWN_NET_AMT AS DECIMAL(25,5)), 0) as DRAWDOWN_NET_AMT,
    COALESCE(CAST(ld.EXCG_RATE AS DECIMAL(13,7)), 0) as EXCG_RATE,
    TRIM(ld.FCC_LIMIT) as FCC_LIMIT,
    {{ t24_date('ld.FIN_MAT_DATE') }} as FIN_MAT_DATE,
    TRIM(ld.ID) as ID,
    TRIM(ld.INPUTTER) as INPUTTER,
    TRIM(ld.INT_LIQ_ACCT) as INT_LIQ_ACCT,
    TRIM(ld.INT_RATE_TYPE) as INT_RATE_TYPE,
    {{ t24_date('ld.INT_VALUE_DATE') }} as INT_VALUE_DATE,
    COALESCE(CAST(ld.INTEREST_RATE AS DECIMAL(13,7)), 0) as INTEREST_RATE,
    COALESCE(CAST(ld.INTEREST_SPREAD AS DECIMAL(13,7)), 0) as INTEREST_SPREAD,
    TRIM(ld.LIMIT_REFERENCE) as LIMIT_REFERENCE,
    TRIM(ld.LOC_TERM) as LOC_TERM,
    TRIM(ld.LOS_FAC_CODE) as LOS_FAC_CODE,
    {{ etl_date() }} as ETL_DATE
from ld
left join cus on ld.CUSTOMER_ID = cus.RECID
left join dao on ld.MB_RM_BANCHEO = dao.RECID
